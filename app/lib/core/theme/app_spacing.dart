/// Standard spacing values (padding/gaps) used across the app.
/// Keeping these in one place is what gives the whole app a consistent,
/// premium rhythm instead of an ad-hoc look.
class AppSpacing {
  const AppSpacing._();

  static const double xs = 4;
  static const double sm = 8;
  static const double md = 12;
  static const double lg = 16;
  static const double xl = 24;
  static const double xxl = 32;

  /// Standard rounded-corner radius for cards and buttons.
  static const double radius = 16;

  /// Slightly tighter radius for inputs.
  static const double radiusInput = 12;
}
